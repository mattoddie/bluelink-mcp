"""Generate docs/tools.md from the tool definitions.

uv run python scripts/gen_tool_docs.py          # write docs/tools.md
uv run python scripts/gen_tool_docs.py --check  # fail if it is out of date (CI)
"""

from __future__ import annotations

import sys
from pathlib import Path
from typing import Any

import anyio

from bluelink_mcp.config import Config
from bluelink_mcp.server import build_server

OUT = Path(__file__).resolve().parent.parent / "docs" / "tools.md"

# Sections of the reference, in order. Every tool must appear in exactly one.
GROUPS: list[tuple[str, str, list[str]]] = [
    (
        "status",
        "The car's state as Bluelink last heard it, live refreshes, location and command results.",
        [
            "list_vehicles",
            "get_vehicle_status",
            "refresh_vehicle_status",
            "get_vehicle_location",
            "get_command_status",
        ],
    ),
    ("history", "Driving history and daily energy use.", ["get_trips", "get_energy_usage"]),
    (
        "climate",
        "Pre-conditioning the cabin: temperature, defrost, heated rear window, steering wheel and seats.",
        ["start_climate", "stop_climate"],
    ),
    (
        "charging",
        "Starting and stopping charging, and charge limits.",
        ["start_charging", "stop_charging", "set_charge_limits"],
    ),
    ("security", "Locks and hazard lights.", ["lock_vehicle", "unlock_vehicle", "flash_hazard_lights"]),
]

LABELS = {"read": "🟢 read", "write": "🟠 write", "unlock": "🔴 unlock"}

BASE_ENV = {"BLUELINK_USERNAME": "docs@example.com", "BLUELINK_PASSWORD": "docs", "BLUELINK_TOKEN_FILE": ""}


async def tools_for(**env: str) -> dict[str, Any]:
    server = build_server(Config.from_env({**BASE_ENV, **env}))
    return {t.name: t for t in await server.list_tools()}


def type_of(schema: dict[str, Any]) -> str:
    if "enum" in schema:
        return " \\| ".join(f"`{v}`" for v in schema["enum"])
    if "anyOf" in schema:
        parts = [type_of(s) for s in schema["anyOf"] if s.get("type") != "null"]
        return " \\| ".join(parts)
    return schema.get("type", "any")


def cell(text: Any) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ").strip()


def arguments(schema: dict[str, Any]) -> str:
    props: dict[str, Any] = schema.get("properties", {})
    if not props:
        return "_No arguments._"
    required = set(schema.get("required", []))
    rows = ["| Argument | Type | Required | Default | Description |", "|---|---|---|---|---|"]
    for name, prop in props.items():
        default = prop.get("default")
        rows.append(
            "| `{}` | {} | {} | {} | {} |".format(
                name,
                type_of(prop),
                "yes" if name in required else "",
                f"`{str(default).lower() if isinstance(default, bool) else default}`"
                if default is not None
                else "",
                cell(prop.get("description", "")),
            )
        )
    return "\n".join(rows)


def describe(text: str | None) -> str:
    # Docstrings wrap lines; join them back into paragraphs.
    paras = [" ".join(line.strip() for line in p.splitlines()) for p in (text or "").strip().split("\n\n")]
    return "\n\n".join(p for p in paras if p)


def render() -> str:
    read = anyio.run(tools_for)
    write = anyio.run(lambda: tools_for(BLUELINK_ALLOW_WRITES="true"))
    every = anyio.run(lambda: tools_for(BLUELINK_ALLOW_WRITES="true", BLUELINK_ALLOW_UNLOCK="true"))

    def level(name: str) -> str:
        return "read" if name in read else "write" if name in write else "unlock"

    grouped = [n for _, _, names in GROUPS for n in names]
    missing = sorted(set(every) - set(grouped))
    unknown = sorted(set(grouped) - set(every))
    if missing or unknown or len(grouped) != len(set(grouped)):
        sys.exit(f"gen_tool_docs: fix GROUPS (missing {missing}, unknown {unknown}, or duplicates)")

    counts = {k: sum(1 for n in every if level(n) == k) for k in LABELS}
    out = [
        "# Tool reference",
        "",
        "<!-- Generated by `uv run python scripts/gen_tool_docs.py` from the tool definitions. "
        "Do not edit by hand. -->",
        "",
        f"bluelink-mcp has **{len(every)} tools** in **{len(GROUPS)} groups**: "
        f"{counts['read']} read, {counts['write']} write and {counts['unlock']} unlock.",
        "",
        "Each tool is labelled with the setting it needs:",
        "",
        "| Label | Registered when |",
        "|---|---|",
        "| 🟢 read | Always |",
        "| 🟠 write | `BLUELINK_ALLOW_WRITES=true` |",
        "| 🔴 unlock | `BLUELINK_ALLOW_WRITES=true` and `BLUELINK_ALLOW_UNLOCK=true` |",
        "",
        "Every tool takes an optional `vehicle` (name, VIN or ID), which you can leave out when the "
        "account has one car. Commands wait for the car to confirm by default (`wait`), which "
        "usually takes 20 to 60 seconds.",
        "",
        "## Contents",
        "",
        *[f"- [`{g}`](#{g}): {summary}" for g, summary, _ in GROUPS],
        "",
    ]
    for group, summary, names in GROUPS:
        out += [f"## {group}", "", summary, "", "| Tool | Access | Summary |", "|---|---|---|"]
        for n in names:
            out.append(f"| [`{n}`](#{n}) | {LABELS[level(n)]} | {cell(every[n].title)} |")
        out.append("")
        for n in names:
            tool = every[n]
            out += [
                f"### {n}",
                "",
                LABELS[level(n)],
                "",
                describe(tool.description),
                "",
                arguments(tool.input_schema),
                "",
            ]
    return "\n".join(out).rstrip() + "\n"


def main() -> None:
    text = render()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            sys.exit("docs/tools.md is out of date. Run: uv run python scripts/gen_tool_docs.py")
        print("docs/tools.md is up to date")
        return
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(Path.cwd()) if OUT.is_relative_to(Path.cwd()) else OUT}")


if __name__ == "__main__":
    main()
